/** The glyph rows for one character: capitals for lowercase, '?' for anything the font lacks. */
export const glyphFor = (ch: string): readonly string[] => GLYPHS[ch.toUpperCase()] ?? GLYPHS['?']!

/** Width in cells of `text` at `scale`, without trailing spacing. */
export const textWidth = (text: string, scale = 1): number => ([...text].length * FONT_ADVANCE - (FONT_ADVANCE - FONT_WIDTH)) * scale

/** Call `plot(x, y)` for every inked cell of `text` with its top-left at (left, top), each font cell `scale` cells square. */
export function drawText(text: string, left: number, top: number, scale: number, plot: (x: number, y: number) => void): void {
  ;[...text].forEach((ch, i) => {
    glyphFor(ch).forEach((row, gy) =>
      [...row].forEach((cell, gx) => {
        if (cell !== '#') return
        for (let dy = 0; dy < scale; dy += 1) for (let dx = 0; dx < scale; dx += 1) plot(left + (i * FONT_ADVANCE + gx) * scale + dx, top + gy * scale + dy)
      }),
    )
  })
}
